def _init_inverse_state(XX, XY, YY, active_idx, ridge=0.0):
    """Build (H, β, SSE) for the active subset from a fresh Cholesky.

    The output that matters is H, the *explicit inverse* of the (loaded) Gram
    matrix. The backward pass downdates H by rank-1 Schur complements and
    needs β_j²/H_jj for each column (see _backward_eliminate). So it needs a
    genuine inverse, and a least-squares solution is not enough. XX_sub = BᵀB
    is symmetric positive semi-definite, so Cholesky is the right
    factorization. It is the fastest for SPD, and one factor serves both the β
    solve and the inverse.

    Diagonal loading is applied in two ways, both as `A + cI`:
      * `ridge`: the caller's regularization, on the standardized scale. So
        the selection here regularizes exactly like the final solve in
        prune().
      * jitter: a last-resort safety net. A Cholesky LinAlgError is an exact
        signal that A is not numerically PD (collinear columns, for example
        overlapping hinges). Loading the diagonal restores a true inverse, so
        the rank-1 downdate identity stays valid. A pseudo-inverse would not
        keep it valid, which is why we load the diagonal instead of falling
        back to pinv/lstsq.

    With ridge==0 on a well-conditioned subset, both are no-ops, so the
    default path is unchanged. SSE is the penalized objective YY − XYᵀβ that
    the sweep telescopes. For a stabilizer-sized ridge, it differs from the
    raw RSS by λ‖β‖².
    """
    m = len(active_idx)
    if m == 0:
        return np.zeros((0, 0)), np.zeros(0), float(YY)

    XX_sub = XX[np.ix_(active_idx, active_idx)]
    XY_sub = XY[active_idx]

    A = XX_sub + ridge * np.eye(m) if ridge > 0 else XX_sub
    try:
        L = np.linalg.cholesky(A)
    except np.linalg.LinAlgError:
        jitter = 1e-8 * (np.trace(A) / m + 1.0)
        L = np.linalg.cholesky(A + jitter * np.eye(m))

    cho = (L, True)
    beta = scipy.linalg.cho_solve(cho, XY_sub)
    H = scipy.linalg.cho_solve(cho, np.eye(m))
    SSE = max(float(YY - XY_sub @ beta), 0.0)
    return H, beta, SSE


def _backward_eliminate(XX, XY, YY, mask, penalty, n_true, ridge=0.0):
    """
    Backward stepwise selection with Schur-complement updates.

    Maintains H = (XX_active + ridge·I)⁻¹ and β = H · XY_active. Each step
    drops the candidate with the smallest ΔSSE_j = β_j² / H_jj and updates H
    and β by rank-1. The total cost is O(M³), vs. O(M⁵) for a full re-solve
    per candidate. A periodic Cholesky refresh bounds the drift. The intercept
    (global column 0) is never dropped.
    """
    M = len(XX)
    active_idx = np.where(mask)[0]
    m = len(active_idx)
    if m == 0:
        return mask.copy()

    H, beta, SSE = _init_inverse_state(XX, XY, YY, active_idx, ridge)

    def _gcv(sse, mm):
        dof = mm + penalty * (mm - 1)
        denom = 1.0 - dof / n_true
        return sse / (denom * denom) if denom > 0 else np.inf

    best_gcv = _gcv(SSE, m)
    best_mask = mask.copy()

    refresh_every = max(64, M // 4)
    since_refresh = 0

    while m > 0:
        diag_H = np.diag(H)
        tol = 1e-12 * max(float(diag_H.max()), 1.0)
        cand = np.full_like(beta, np.inf)
        np.divide(beta * beta, diag_H, out=cand, where=diag_H > tol)

        if active_idx[0] == 0:
            cand[0] = np.inf

        j = int(np.argmin(cand))
        if not np.isfinite(cand[j]):
            break

        SSE = SSE + max(float(cand[j]), 0.0)

        h_col = H[:, j]
        v = h_col / H[j, j]
        beta = beta - beta[j] * v
        H = H - np.outer(v, h_col)
        H = 0.5 * (H + H.T)
        np.fill_diagonal(H, np.maximum(np.diag(H), 0.0))

        beta = np.delete(beta, j)
        H = np.delete(np.delete(H, j, axis=0), j, axis=1)
        mask[active_idx[j]] = False
        active_idx = np.delete(active_idx, j)
        m -= 1

        since_refresh += 1
        if since_refresh >= refresh_every and m > 0:
            H, beta, SSE = _init_inverse_state(XX, XY, YY, active_idx, ridge)
            since_refresh = 0

        gcv = _gcv(SSE, m)
        if gcv < best_gcv:
            best_gcv = gcv
            best_mask = mask.copy()

    return best_mask


def prune(B, y, w=None, n_true=None, penalty=3.0, ridge=0.0, mask=None):
    """
    Solve for the linear coefficients using backward stepwise selection
    (GCV pruning), following Friedman (1991) §3.4.

    The intercept (column 0 of `B`, by the `fit()`/`expand()` convention) is
    never removed.

    prune() standardizes the columns of B internally (unit diagonal of the
    Gram matrix), so that `ridge` has the same effect on every feature. The
    returned coefficients are on the original (un-standardized) scale.

    Parameters
    ----------
    B : array (n, M)
        Basis matrix from `expand()`.

    y : array (n,)
        Target vector.

    w : array (n,) or None
        Observation weights for WLS. None means uniform. The objective is
        `Σ wᵢ(yᵢ - f(xᵢ))²`, so pass `1/σ²` for heteroskedastic fitting.

    n_true : int or None
        Number of truly independent samples for GCV. None means len(B).

    penalty : float (default=3)
        GCV smoothing penalty. See the `fit()` parameter of the same name.

    ridge : float (default=0)
        L2 regularization applied on the standardized scale.

    mask : bool array (M,) or None
        Initial mask of which basis terms to consider. None means all.

    Returns
    -------
    beta : array (M,)
        Coefficient vector. Pruned terms have coefficient 0.
    """

    n, M = B.shape
    if n_true is None:
        n_true = n

    y_valid = np.isfinite(y)
    if not y_valid.all():
        if w is None:
            w = np.ones(len(y), dtype=B.dtype)
        w = np.where(y_valid, w, 0)
        y = np.where(y_valid, y, 0)

    # Fold weights into B and y via sqrt(w) so WLS becomes plain OLS
    if w is not None:
        sw = np.sqrt(np.asarray(w, dtype=B.dtype))
        B = B * sw[:, np.newaxis]
        y = y * sw

    # Compute Gram matrices with float64 accumulation
    XX = gram(B)
    XY = gram(B, y)
    YY = gram(y, y)

    # Standardize columns so diag(XX) == 1 on active columns
    d = np.sqrt(np.diag(XX))
    active = d > 0
    d_safe = np.where(active, d, 1.0)
    XX = XX / d_safe / d_safe[:, np.newaxis]
    XY = XY / d_safe

    # Backward elimination returns the GCV-best subset. We re-solve from
    # scratch below, so the returned coefficients are free of any drift.
    # `ridge` also enters the selection (diagonal loading in
    # _init_inverse_state), so the subset is chosen under the same
    # regularization as the final solve.
    mask = np.array(mask) if mask is not None else np.ones(M, dtype="bool")
    mask = mask & active
    best_mask = _backward_eliminate(XX, XY, YY, mask, penalty, n_true, ridge)

    if ridge > 0:
        # Same diagonal loading as selection, now on the full active Gram.
        XX = XX + np.eye(len(XX)) * ridge
    beta = np.zeros(M)
    if best_mask.any():
        # lstsq handles under-determined sub-problems gracefully
        beta[best_mask] = np.linalg.lstsq(
            XX[np.ix_(best_mask, best_mask)], XY[best_mask], rcond=None
        )[0]
    return beta / d_safe


