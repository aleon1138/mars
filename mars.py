def compact(model):
    """
    Remove pruned basis nodes and return a smaller model.

    compact() keeps the nodes with a non-zero `beta` (the fitted coefficient
    stored on the model, usually filled in by `prune()`). It also keeps every
    ancestor that those nodes need as parents. Ancestors kept only for that
    reason keep their `beta` of zero.

    Parameters
    ----------
    model : structured array
        Model array as returned by `fit()`, with `model["beta"]` populated
        (e.g. `model["beta"] = prune(expand(X, model), y)`).

    Returns
    -------
    model : structured array
        Compacted model with pruned nodes removed and parent pointers remapped.
    """
    keep = model["beta"] != 0

    # Parents always have a lower index than their children, so one reverse
    # sweep propagates the ancestor flag all the way up the chain.
    for i in range(len(model) - 1, 0, -1):
        if keep[i] and model[i]["type"] != b"i":
            keep[model[i]["basis"]] = True

    # Remap parent pointers to the new (compacted) indices.
    new_idx = np.full(len(model), -1, dtype="i4")
    new_idx[keep] = np.arange(keep.sum())

    new_model = model[keep].copy()
    new_model["basis"] = new_idx[new_model["basis"]]
    return new_model


