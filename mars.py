def pprint(model, beta=None, labels=None):
    """
    Pretty-print the model. Useful for debugging.

    Coefficients are taken from `model["beta"]` by default; pass `beta` to
    override with an explicit coefficient vector.
    """
    if beta is None:
        beta = model["beta"]

    def xcol(i):
        if labels is not None:
            return labels[i]
        return "X[%d]" % i

    def get_inputs(i: int):
        row = model[i]
        if row["type"] == b"+":
            node = "MAX(%s%+g,0)" % (xcol(row["input"]), -row["hinge"])
        elif row["type"] == b"-":
            node = "MAX(%g-%s,0)" % (row["hinge"], xcol(row["input"]))
        else:
            node = xcol(row["input"])

        if row["basis"] > 0:
            return [node] + get_inputs(row["basis"])
        return [node]

    for i in range(len(model)):
        bstr = "  "
        if beta is not None and hasattr(beta, "__getitem__"):
            bstr += "%+9.4g" % beta[i]
        if model[i]["type"] != b"i":
            bstr += " * " + " * ".join(get_inputs(i))
        print(bstr)
