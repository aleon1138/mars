def fit(X, y, w=None, **kwargs):
    """
    Multivariate Adaptive Regression Splines

    A flexible regression method that automatically searches for interactions
    and non-linear relationships.

    Parameters
    ----------
    w : array (n,) (default=None)
        Observation weights for weighted least squares. None means uniform.
        The fitted objective is `Σ wᵢ(yᵢ - f(xᵢ))²`, so `w = 1/σ²` for
        heteroskedastic fitting, or relative importance weights otherwise.
        This matches R's `lm(weights=)`, statsmodels, and sklearn semantics.

    max_terms : int (default=1 + 2*min(p + n/20, 15)), where X is (n x p)
        The maximum number of basis functions (model terms), including the
        intercept. The forward pass stops once the basis reaches this many
        terms (or an early-stopping condition fires). Clamped so the degrees
        of freedom never exceed the sample count.

    max_degree : int (default=3)
        The maximum degree of terms generated by the forward pass.

    max_basis : int or None (default=None)
        Fast-MARS: per epoch, reconsider only the `max_basis` highest-priority
        existing basis functions as split parents (earth's `fast.k`). None
        considers all of them (Fast-MARS restriction off). Independent of
        `max_terms`.

    aging_factor : float (default=1.0)
        Fast-MARS aging coefficient (earth's `fast.beta`; Friedman 1993,
        sec 3.1). A parent's priority is the rank of its cached improvement
        plus `aging_factor` times the number of epochs since it was last
        scored, so parents that fell out of the top `max_basis` are retried
        eventually instead of starving. Only matters when `max_basis` is set.

    penalty : float (default=3.0)
        A smoothing parameter used to calculate GCV R².
        Used during the pruning pass and to determine whether to add a hinge
        or linear basis function during the forward pass.
        See the 'd' parameter in equation 32, Friedman, 1991.

    min_span: int (default=None)
        The minimum gap, in number of observations along sorted x, between any
        two candidate knots considered in a single forward step. This helps
        with matrix conditioning at higher orders. The default uses Freidman's
        formula.

    tail_span : float (default=0.02)
        Fraction of samples at the tails of the training data to ignore.
        Prevents hinge formation at the extreme tails of the input range.

    max_runtime : float (default=48*3600)
        Maximum runtime in seconds.

    self_interact : bool (default=False)
        Allow an input to interact with itself. This may cause some numerical
        instability and is best modelled with a linear hinge instead.

    linear_only : bool (default=False)
        Disable formation of any hinges. This will still find interactions
        of inputs.

    n_true : int (default=n), where X is (n x p)
        Allows for an adjustment in the number of truly independent samples
        in the data.

    logger : file-like (default=None)
        A file-like object which can be used to log runtime messages.

    callback : callable (default=None)
        Can be used to get progress updates on the following:
          * current epoch
          * number of basis found
          * the term budget (max_terms)
          * a dict with information about the last basis found

    r2_window : int (default=32)
        Early-stopping patience: stop if GCV R² has not set a new (near-)best
        value in the last `r2_window` epochs.

    r2_thresh : float (default=3e-5)
        Tolerance used with `r2_window`: an epoch's GCV R² counts as a new
        best if it is within `r2_thresh` of the best seen so far. Also used
        as the "essentially perfect fit" threshold (stop when R² > 1 - r2_thresh).

    labels : list-like (default=None)
        A list of column labels. This is only used for console output.

    xfilter : callable or None (default=None)
        Custom candidate filter `xfilter(i, b) -> bool`, where `i` is the input
        column and `b` the list of inputs already in the parent basis. Called
        only for candidates that pass the degree / self-interaction filter.

    threads : int (default=-1)
        Number of cores to use. A negative number implies usage of all cores.

    cuda : bool (default=False)
        Run the forward-pass orthonormalize step on the GPU (requires a CUDA
        build, i.e. USE_CUDA=ON). Most effective in the `linear_only` regime,
        where the candidate columns are batched into large GEMMs; the GPU path
        is driven single-threaded (`threads` is ignored for it).

    Returns
    -------
    model : structured numpy array
        One row per basis function (intercept at index 0). Fields:
            type   S1  -- b'i' intercept, b'l' linear, b'+'/b'-' hinges
            basis  i4  -- index of parent basis row
            input  i4  -- column index into X
            hinge  f8  -- hinge cut point (NaN for linear/intercept)
            beta   f4  -- fitted coefficient; NaN until prune() fills it in
            r2     f4  -- in-sample R² when this row was added
            r2_cv  f4  -- GCV-adjusted R² (out-of-sample estimate)
            order  i4  -- polynomial degree
            time   f4  -- seconds since fit() started
    """

    if w is None:
        w = np.ones(len(X), dtype="f")

    X = np.asarray(X, copy=False)  # do not make a copy of this data!
    y = np.asarray(y.squeeze(), dtype="f")
    w = np.asarray(w.squeeze(), dtype="f")

    assert X.dtype == "f", "X data must be 32-bit float"
    assert X.strides[0] == X.itemsize, "X data must be column-major"
    assert y.strides[0] == y.itemsize, "y data must be column-major"
    assert len(X) == len(y) == len(w), "input dataset length mismatch"
    assert len(X) > 0, "empty dataset"

    # fmt: off
    max_terms     = kwargs.pop('max_terms', 1 + 2*min(X.shape[1]+len(X)//20, 15))
    max_degree    = kwargs.pop('max_degree', 3)
    penalty       = kwargs.pop('penalty', 3.0)
    min_span      = kwargs.pop('min_span', None)
    tail_span     = kwargs.pop('tail_span', 0.02)
    max_runtime   = kwargs.pop('max_runtime', 48*3600) # in seconds
    self_interact = kwargs.pop('self_interact', False)
    linear_only   = kwargs.pop('linear_only', False)
    n_true        = kwargs.pop('n_true', len(X))
    logger        = kwargs.pop('logger', None)
    callback      = kwargs.pop("callback", None)
    r2_window     = kwargs.pop('r2_window', 32) # window over which to measure R2
    r2_thresh     = kwargs.pop('r2_thresh', 3e-5)
    labels        = kwargs.pop('labels', None)
    xfilter       = kwargs.pop('xfilter', None)
    max_basis     = kwargs.pop('max_basis', None)         # Fast-MARS parent cap; None = all
    aging_factor  = kwargs.pop('aging_factor', 1.0)
    threads       = kwargs.pop('threads', -1)
    cuda          = kwargs.pop('cuda', False)
    # fmt: on

    if kwargs:
        raise TypeError("unknown argument: %s" % kwargs)

    start_t = time.time()

    # Coarse profiling (MARS_CUDA_PROFILE): split fit() wall time into the
    # algo.eval() forward-search call (GPU-accelerated under cuda=True) vs all
    # the surrounding CPU orchestration, to tell GPU-bound from Amdahl-bound.
    _profile = bool(os.environ.get("MARS_CUDA_PROFILE"))
    _eval_t = 0.0

    # For reference, see Eq. (43) in the original MARS paper
    if min_span is None:
        alpha = 1 / X.shape[1]
        min_span = int(-np.log2(-np.log(1 - alpha) / (n_true * alpha)) / 2.5)
    min_span = max(min_span, 1)

    get_dof = lambda m: m + penalty * (m - 1)  # Eq. (31,32)
    gcv_adj = lambda mse, m: mse / (1.0 - get_dof(m) / n_true) ** 2  # Eq. (30)

    # Clamp the requested term budget so the DOF never exceed the sample count.
    terms = np.arange(1, max_terms + 1)
    max_terms = int(terms[get_dof(terms) < n_true].max())

    n, n_inputs = X.shape
    end_span = max(int(n * tail_span), 1)
    algo = marslib.MarsAlgo(X, y, w, max_terms)
    var_y = algo.yvar()

    # Per-basis state, preallocated to max_terms and sliced to the live count m.
    # `basis` keeps each term's inputs in insertion order for xfilter; `degree`
    # and `contains[i, k] = (i in basis[k])` are the same information as arrays
    # so the degree / self-interaction filter is a block operation. The
    # Fast-MARS parent cache holds the best delta-SSE each basis produced as a
    # parent the last time it was scored, and that epoch; a new basis enters at
    # +inf so it is scored at least once before competing on its own gain.
    basis     = [[]]
    degree    = np.zeros(max_terms, dtype=np.int64)
    contains  = np.zeros((n_inputs, max_terms), dtype=bool)
    basis_sse = np.full(max_terms, np.inf)
    basis_age = np.zeros(max_terms, dtype=np.int64)
    epoch = 0

    # Define output data structure
    # fmt: off
    model = np.zeros(
        max_terms,
        dtype=[
            ("type",  "S1"),
            ("basis", "i4"),
            ("input", "i4"),
            ("hinge", "f8"),
            ("beta",  "f4"),
            ("r2",    "f4"),
            ("r2_cv", "f4"),
            ("order", "i4"),
            ("time",  "f4"),
        ],
    )
    model[0] = ("i", 0, 0, np.nan, np.nan, 0, 0, 0, 0)  # add the intercept
    # fmt: on

    _dump_header(logger)

    def _ranks(x):
        r = np.empty(len(x), dtype=np.intp)
        r[np.argsort(x, kind="stable")] = np.arange(len(x))
        return r

    while algo.nbasis() < max_terms:
        m0 = m = algo.nbasis()

        # Fast MARS (Friedman 1993, sec 3.0-3.1; earth's fast.k / fast.beta):
        # reconsider only the `max_basis` parents of highest priority, where
        # priority = rank of the cached improvement + aging_factor * epochs since
        # it was last scored. Without the aging term a parent that once fell out
        # of the top K keeps a stale score and is never retried. With
        # max_basis=None every parent is selected and the order is irrelevant.
        priority = _ranks(basis_sse[:m]) + aging_factor * (epoch - basis_age[:m])
        basis_to_use = np.argsort(priority, kind="stable")[::-1][:max_basis]

        # The (input, basis) candidate mask for this epoch.
        bmask = np.zeros((n_inputs, m), dtype=bool)
        bmask[:, basis_to_use] = True
        bmask &= degree[None, :m] < max_degree
        if not self_interact:
            bmask &= ~contains[:, :m]
        if xfilter is not None:
            for i, k in zip(*np.nonzero(bmask)):
                bmask[i, k] = bool(xfilter(i, basis[k]))

        # Delta-SSE of every candidate: sse1 for a linear term, sse2 for the
        # mirrored hinge pair at the best cut.
        _e0 = time.perf_counter()
        sse0, sse1, sse2, cut = algo.eval(
            bmask, min_span, end_span, linear_only, threads, cuda=cuda
        )
        _eval_t += time.perf_counter() - _e0

        # Re-score every parent tried this epoch with the best gain over its
        # candidates (0 if the filters left none, which also retires a basis
        # that can never be a parent again, e.g. one at max_degree). sse2 (hinge
        # pair) is >= sse1 wherever a cut was found, but it is 0 in linear_only
        # mode and wherever no admissible cut exists, hence the elementwise max.
        basis_sse[basis_to_use] = np.maximum(sse1, sse2)[:, basis_to_use].max(axis=0)
        basis_age[basis_to_use] = epoch
        epoch += 1

        j1 = np.unravel_index(np.argmax(sse1), sse1.shape)
        j2 = np.unravel_index(np.argmax(sse2), sse2.shape)
        dt = time.time() - start_t
        if sse1[j1] <= 0 and sse2[j2] <= 0:
            break  # all input data is filtered or zero

        # Estimate the out-sample error with Generalized Cross-Validation
        mse1 = gcv_adj((1.0 - sse0 - sse1[j1]) / n, m + 1)
        mse2 = gcv_adj((1.0 - sse0 - sse2[j2]) / n, m + 2)
        if mse1 <= mse2:
            xcol, bcol, hcut = j1[0], j1[1], np.nan
            htypes = ["l"]
        else:
            xcol, bcol, hcut = j2[0], j2[1], cut[j2]
            htypes = ["+", "-"]

        for htype in htypes:
            # Respect the term budget: a hinge pair adds two basis, so the
            # second one must not push us past max_terms (the loop condition
            # only guarantees room for one).
            if algo.nbasis() >= max_terms:
                break
            # append() returns -1 for a numerically degenerate column; an exact
            # 0 (noise-free y) is a valid fit.
            mse = algo.append(htype, xcol, bcol, hcut)
            if mse >= 0:
                # fmt:off
                basis.append(basis[bcol] + [xcol])
                degree[m]         = degree[bcol] + 1
                contains[:, m]    = contains[:, bcol]
                contains[xcol, m] = True
                basis_sse[m]      = np.inf
                basis_age[m]      = epoch
                model[m] = (
                    htype,                              # type
                    bcol,                               # basis
                    xcol,                               # input
                    hcut,                               # hinge
                    np.nan,                             # beta (NaN until prune fills it)
                    1.0 - mse / var_y,                  # r2
                    1.0 - gcv_adj(mse, m + 1) / var_y,  # r2_cv
                    degree[m],                          # order
                    dt,                                 # time
                )
                m += 1
                # fmt:on
        assert algo.nbasis() == len(basis) == m

        if logger:
            _dump_row(logger, epoch, m, dt, model[m - 1], labels)
        if callback:
            callback(epoch, m, max_terms, model[m - 1])

        # Stopping conditions
        if m == m0:
            break  # no progress
        if model[m - 1]["r2"] > 1 - r2_thresh:
            break  # R2 almost reached 100%
        if dt > max_runtime:
            break  # exceed max runtime

        # Patience: stop if no new (near-)best GCV R² in the last r2_window epochs.
        r2_cvs = model["r2_cv"][: algo.nbasis()]
        if (
            len(r2_cvs) > r2_window
            and r2_cvs[-r2_window:].max() < r2_cvs.max() - r2_thresh
        ):
            break

    if _profile:
        total = time.time() - start_t
        pct = (100.0 * _eval_t / total) if total else 0.0
        sys.stderr.write(
            "[mars] fit: %.2fs total | %.2fs in algo.eval() (%.0f%%) | "
            "%.2fs orchestration (%d epochs)\n"
            % (total, _eval_t, pct, total - _eval_t, epoch)
        )

    return model[: algo.nbasis()]


